package lab.owmcguest;

import net.minecraft.server.network.ServerPlayerEntity;
import net.minecraft.server.world.ServerWorld;
import net.minecraft.entity.LivingEntity;
import net.minecraft.util.math.*;
import net.minecraft.world.explosion.Explosion;
import net.minecraft.particle.ParticleTypes;
import net.minecraft.sound.*;

/** Native E factory/flight, real MC radial push. Exact OW impulse curve remains
 * unverified: this explicitly uses MC explosion-style exposure/falloff/velocity. */
public final class NativeConcussiveRuntime {
    public static final long HERO=0x02e0000000000008L;
    public record SelfCue(java.util.UUID owner,long source,long world,long model,long id,long wall,Vec3d velocity){}
    public static volatile SelfCue selfCue;
    public static volatile String status="{}";
    private static long detonations,pushed,selfPushed;
    public static double detonate(ServerWorld world,ServerPlayerEntity player,NativeShotProtocol.Shot shot,NativeShotSimulation.Hit hit,NativeShotProtocol.Source source){
        if(shot.effect()==null||shot.effect().kind()!=3||!hit.loaded())return 0;
        var at=new Vec3d(hit.point().x(),hit.point().y(),hit.point().z());
        var normal=hit.normal();var incoming=new Vec3d(shot.velocity().x(),shot.velocity().y(),shot.velocity().z()).normalize();
        var origin=hit.block()&&normal!=null?at.add(normal.x()*.025,normal.y()*.025,normal.z()*.025):at.subtract(incoming.multiply(.025));
        if(!world.isChunkLoaded(BlockPos.ofFloored(origin)))return 0;
        double radius=shot.effect().radius(),healthLost=0;detonations++;
        PharahConcussiveBursts.impact(shot,hit);
        // The client draws the pressure shell; a little residual air replaces
        // the old opaque generic explosion/cloud ball. Latest user exception
        // preserves this pressure effect without any added terrain explosion.
        world.spawnParticles(ParticleTypes.CLOUD,origin.x,origin.y,origin.z,8,.1,.1,.1,.08);
        world.playSound(null,at.x,at.y,at.z,SoundEvents.ENTITY_GENERIC_EXPLODE,SoundCategory.PLAYERS,.65f,1.65f);
        var targets=new java.util.ArrayList<>(NativeDamageTargets.in(world,player,new Box(origin,origin).expand(radius)));targets.add(player);
        record Candidate(net.minecraft.entity.Entity part,LivingEntity target,double scale,Vec3d impulse){}
        var candidates=new java.util.LinkedHashMap<java.util.UUID,Candidate>();
        for(var part:targets){
            var target=NativeDamageTargets.owner(part);
            if(!(target instanceof LivingEntity living)||!target.isAlive()||!world.isChunkLoaded(target.getBlockPos()))continue;
            var center=part.getBoundingBox().getCenter();var delta=center.subtract(origin);double distance=delta.length();
            if(distance>=radius||distance<1e-6)continue;
            // Every exposure sample stays in loaded terrain. An unavailable
            // neighboring chunk must not become synchronously generated by E.
            var box=part.getBoundingBox();boolean loaded=true;
            if(box.getLengthX()>64||box.getLengthY()>64||box.getLengthZ()>64)continue;
            for(int x=(int)Math.floor(Math.min(origin.x,box.minX))>>4;x<=((int)Math.floor(Math.max(origin.x,box.maxX))>>4);x++)
                for(int z=(int)Math.floor(Math.min(origin.z,box.minZ))>>4;z<=((int)Math.floor(Math.max(origin.z,box.maxZ))>>4);z++)
                    if(!world.isChunkLoaded(new BlockPos(x<<4,(int)origin.y,z<<4)))loaded=false;
            if(!loaded)continue;
            // One block/tick is MC's unit full-exposure blast impulse. Do not
            // label the beta's undocumented1/1/1 slots as an OW velocity.
            // Exposure already tests cover. A second center ray incorrectly
            // rejected partly exposed creatures and multipart bosses entirely.
            double scale=(1-distance/radius)*Explosion.getExposure(origin,part);if(scale<=0)continue;
            var impulse=delta.multiply(scale/distance);
            var previous=candidates.get(target.getUuid());
            if(previous==null||scale>previous.scale())candidates.put(target.getUuid(),new Candidate(part,living,scale,impulse));
        }
        for(var candidate:candidates.values()){
            var target=candidate.target();var impulse=candidate.impulse();
            if(target==player){
                long w=NativeWorldIdentity.of(world.getServer(),world.getRegistryKey());long model=NativeEliminationRuntime.scopedModel(player.getUuid(),w,HERO,source.hostGeneration());
                if(model==0)continue;
                selfCue=new SelfCue(player.getUuid(),source.hostGeneration(),w,model,shot.id(),System.currentTimeMillis(),impulse);selfPushed++;
            }else{
                // User-requested stronger enemy push; self propulsion stays at
                // the accepted baseline. Five OW-equivalent HP is a custom
                // adaptation, not a claim about either beta or current damage.
                var beforeVelocity=target.getVelocity();var beforePosition=target.getPos();
                healthLost+=NativeDamageTargets.explosionDamage(world,candidate.part(),player,.5*candidate.scale()).healthLost();
                // DamageSource(player) has its own vanilla attacker-directed
                // knockback. Do not add that unrelated vector to the radial E.
                // A damage reaction that teleported/removed a target is final.
                if(target.isAlive()&&!target.isRemoved()&&target.getWorld()==world&&target.getPos().squaredDistanceTo(beforePosition)<1e-8){
                    target.setVelocity(beforeVelocity.add(impulse.multiply(1.5)));target.velocityModified=true;pushed++;
                }
            }
        }
        var o=new com.google.gson.JsonObject();o.addProperty("terrainBursts",0);o.addProperty("terrainBlocks",0);o.addProperty("terrainStrength",NativeExplosionTerrain.CONCUSSIVE);o.addProperty("terrainError","");o.addProperty("terrainPolicy","explicit-user-exception");o.addProperty("detonations",detonations);o.addProperty("pushed",pushed);o.addProperty("selfPushed",selfPushed);o.addProperty("radius",radius);o.addProperty("healthLost",healthLost);o.addProperty("maxHealthDamage",.5);o.addProperty("enemyImpulseMultiplier",1.5);o.addProperty("physics","User custom enemy boost; MC radial impulse adapter; self unchanged");status=o.toString();return healthLost;
    }
    public static void resetSession(){selfCue=null;}
}
