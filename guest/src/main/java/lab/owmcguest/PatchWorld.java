package lab.owmcguest;

import com.google.gson.JsonParser;
import com.sun.net.httpserver.HttpServer;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.Map;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicInteger;
import net.minecraft.block.Block;
import net.minecraft.block.Blocks;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.network.ServerPlayerEntity;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.GameMode;

/** Only the separately launched singleplayer guest may own this editable lab. */
public final class PatchWorld {
    public static final boolean NEW_WORLD=Boolean.getBoolean("owmc.newWorld");
    public static final boolean CREATIVE=Boolean.getBoolean("owmc.creativeFlat");
    public static final int LOW=CREATIVE?-16:-4,HIGH=CREATIVE?15:3,BOTTOM=CREATIVE?-4:-1,TOP=CREATIVE?7:3;
    public static volatile BlockPos origin;
    private static HttpServer api;
    private static volatile String lastEdit="null";
    private static final AtomicInteger pending=new AtomicInteger(),revision=new AtomicInteger();
    private static final Map<String,Block> ALLOWED=Map.of("minecraft:air",Blocks.AIR,"minecraft:stone",Blocks.STONE,"minecraft:dirt",Blocks.DIRT,
        "minecraft:grass_block",Blocks.GRASS_BLOCK,"minecraft:oak_log",Blocks.OAK_LOG,
        "minecraft:oak_planks",Blocks.OAK_PLANKS,"minecraft:stone_bricks",Blocks.STONE_BRICKS);
    public static void start(MinecraftServer server,ServerPlayerEntity player) {
        if(origin!=null||!server.isSingleplayer()) return;
        BlockPos base=new BlockPos(0,NEW_WORLD?-60:-56,0);var world=player.getServerWorld();
        if(NEW_WORLD) {
            // Generated by Minecraft's own Flat world preset; never seed/replace chunks here.
            player.changeGameMode(GameMode.CREATIVE);
        } else if(CREATIVE) {
            for(int x=LOW;x<=HIGH;x++) for(int z=LOW;z<=HIGH;z++) for(int y=BOTTOM;y<=TOP;y++) {
                Block block=y==-4?Blocks.BEDROCK:y<=-2?Blocks.DIRT:y==-1?Blocks.GRASS_BLOCK:Blocks.AIR;
                world.setBlockState(base.add(x,y,z),block.getDefaultState());
            }
            player.changeGameMode(GameMode.CREATIVE);
        } else {
            for(int x=-4;x<=3;x++) for(int z=-4;z<=3;z++) for(int y=-1;y<=3;y++)
                world.setBlockState(base.add(x,y,z),(y==-1?Blocks.GRASS_BLOCK:Blocks.AIR).getDefaultState());
            for(int x:new int[]{-3,3}) for(int z:new int[]{-3,3}) for(int y=0;y<3;y++)
                world.setBlockState(base.add(x,y,z),Blocks.OAK_LOG.getDefaultState());
            for(int x=-2;x<=2;x++) for(int y=0;y<3;y++) if(x!=0||y==2)
                world.setBlockState(base.add(x,y,3),Blocks.STONE_BRICKS.getDefaultState());
            world.setBlockState(base.add(-2,0,0),Blocks.OAK_PLANKS.getDefaultState());
            world.setBlockState(base.add(-2,1,0),Blocks.OAK_PLANKS.getDefaultState());
        }
        player.teleport(world,.5,base.getY(),0.5,player.getYaw(),player.getPitch());origin=base;
        try {
            api=HttpServer.create(new InetSocketAddress("127.0.0.1",32132),4);
            api.setExecutor(Executors.newFixedThreadPool(2,r->{Thread t=new Thread(r,"owmc-patch-api");t.setDaemon(true);return t;}));
            api.createContext("/",exchange->{
                int code=404;String response="{\"error\":\"route\"}";
                try {
                    if(exchange.getRequestHeaders().containsKey("Origin")) { code=403;response="{\"error\":\"origin\"}"; }
                    else if(exchange.getRequestURI().getPath().equals("/health")&&exchange.getRequestMethod().equals("GET")) {
                        code=200;response="{\"worldReady\":"+(origin!=null)+",\"mode\":\""+(NEW_WORLD?"minecraft-flat-world":CREATIVE?"creative-superflat":"patch-lab")
                            +"\",\"bounds\":["+LOW+","+HIGH+","+BOTTOM+","+TOP+"],\"revision\":"+revision.get()+",\"lastEdit\":"+lastEdit+"}";
                    } else if(exchange.getRequestURI().getPath().equals("/v1/block")&&exchange.getRequestMethod().equals("POST")) {
                        byte[] body=exchange.getRequestBody().readNBytes(1025);
                        if(body.length>1024) { code=413;response="{\"error\":\"body budget\"}"; }
                        else {
                            var json=JsonParser.parseString(new String(body,StandardCharsets.UTF_8)).getAsJsonObject();
                            if(json.size()!=4||!json.get("block").isJsonPrimitive()||!json.get("block").getAsJsonPrimitive().isString()) throw new IllegalArgumentException();
                            int x=integer(json.get("x")),y=integer(json.get("y")),z=integer(json.get("z"));
                            String block=json.get("block").getAsString();Block type=ALLOWED.get(block);
                            if(x<(NEW_WORLD?-1000000:LOW)||x>(NEW_WORLD?1000000:HIGH)||z<(NEW_WORLD?-1000000:LOW)||z>(NEW_WORLD?1000000:HIGH)||y<BOTTOM||y>TOP||type==null||(CREATIVE&&y==BOTTOM)) throw new IllegalArgumentException();
                            if(pending.incrementAndGet()>8) { pending.decrementAndGet();code=429;response="{\"error\":\"queue full\"}"; }
                            else {
                                server.execute(()->{try {
                                    if(type==Blocks.AIR) world.breakBlock(base.add(x,y,z),!CREATIVE,player);
                                    else world.setBlockState(base.add(x,y,z),type.getDefaultState());int applied=revision.incrementAndGet();
                                    lastEdit="{\"revision\":"+applied+",\"x\":"+x+",\"y\":"+y+",\"z\":"+z+",\"block\":\""+block+"\"}";
                                    System.out.println("[OWMCGuest] Actual lab edit applied: "+lastEdit);
                                } finally { pending.decrementAndGet(); }});
                                code=202;response="{\"accepted\":true}";
                            }
                        }
                    } else if(NEW_WORLD&&exchange.getRequestURI().getPath().equals("/v1/observer")&&exchange.getRequestMethod().equals("POST")) {
                        byte[] body=exchange.getRequestBody().readNBytes(513);if(body.length>512) throw new IllegalArgumentException();
                        var json=JsonParser.parseString(new String(body,StandardCharsets.UTF_8)).getAsJsonObject();
                        int x=integer(json.get("x")),z=integer(json.get("z"));
                        if(json.size()!=2||Math.abs(x)>1000000||Math.abs(z)>1000000) throw new IllegalArgumentException();
                        if(pending.incrementAndGet()>8) {pending.decrementAndGet();code=429;response="{\"error\":\"queue full\"}";}
                        else {server.execute(()->{try {
                            player.teleport(world,x+.5,base.getY(),z+.5,player.getYaw(),player.getPitch());
                            centerX=x;centerZ=z;
                        }finally{pending.decrementAndGet();}});code=202;response="{\"accepted\":true}";}
                    } else if(NEW_WORLD&&exchange.getRequestURI().getPath().equals("/save")&&exchange.getRequestMethod().equals("POST")) {
                        server.execute(()->server.save(false,true,false));code=202;response="{\"accepted\":true}";
                    } else if(NEW_WORLD&&exchange.getRequestURI().getPath().equals("/shutdown")&&exchange.getRequestMethod().equals("POST")) {
                        server.execute(()->{server.save(false,true,false);server.stop(false);});code=202;response="{\"accepted\":true}";
                    }
                } catch(RuntimeException error) { code=400;response="{\"error\":\"invalid edit\"}"; }
                byte[] bytes=response.getBytes(StandardCharsets.UTF_8);exchange.getResponseHeaders().set("Content-Type","application/json");
                exchange.sendResponseHeaders(code,bytes.length);try(var output=exchange.getResponseBody()) {output.write(bytes);}finally{exchange.close();}
            });api.start();System.out.println("[OWMCGuest] Independent editable patch ready at "+base);
        } catch(java.io.IOException error) { origin=null;throw new IllegalStateException("Patch API unavailable",error); }
    }
    public static volatile int centerX=0,centerZ=0;
    private static int integer(com.google.gson.JsonElement value) {
        if(value==null||!value.isJsonPrimitive()||!value.getAsJsonPrimitive().isNumber()) throw new IllegalArgumentException();
        return value.getAsBigDecimal().intValueExact();
    }
    public static void close() { if(api!=null) api.stop(0);api=null;origin=null; }
}
